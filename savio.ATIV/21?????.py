a=int(input("Digite o valor de a: "))
b=int(input("Digite o valor de b: "))
c=int(input("Digite o valor de c: "))
d=int(input("Digite o valor de d: "))
if a**2==a:
    print("o valor de", a, "é um quadrado perfeito")
elif b**2==b:
    print("o valor de", b, "é um quadrado perfeito")
elif c**2==c:
    print("o valor de", c, "é um quadrado perfeito")
elif d**2==d: 
    print("o valor de", d, "é um quadrado perfeito")
else:
    print("Nenhum dos números é um quadrado perfeito")